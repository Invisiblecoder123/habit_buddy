/**
 * Calculates the 1-based day of the year for a given date.
 */
export function getDayOfYear(date = new Date()) {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date - start;
  const oneDay = 1000 * 60 * 60 * 24;
  return Math.floor(diff / oneDay);
}

/**
 * Deterministically picks a quote from the fallback pool based on dayOfYear % quotes.length.
 */
export function getDeterministicDailyQuote(quotes = fallbackQuotes, date = new Date()) {
  if (!quotes || quotes.length === 0) {
    return {
      quote: "Discipline equals freedom.",
      author: "Jocko Willink"
    };
  }
  const dayOfYear = getDayOfYear(date);
  const index = Math.abs(dayOfYear) % quotes.length;
  return quotes[index];
}
